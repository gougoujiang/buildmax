package architecture_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestNPMDirectoriesAreSeparateModules guards the root module against Go
// sources that arrive through npm.
//
// The Go tool has no special case for node_modules the way it does for
// testdata, so any Go file an npm package ships lands in the root module's
// `./...` as soon as somebody runs `npm install`. The `flatted` package —
// pulled in transitively by ESLint — ships one, which put
// portal/node_modules/flatted/golang/pkg/flatted into `go build ./...`,
// `go vet ./...`, `go test ./...`, and `go mod tidy`.
//
// The fix is a nested go.mod that takes the npm subtree out of the root
// module. This test keeps the rule from lapsing when a new frontend is added.
func TestNPMDirectoriesAreSeparateModules(t *testing.T) {
	root := moduleRoot(t)

	var npmDirs []string
	if err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "node_modules" || d.Name() == "vendor" || strings.HasPrefix(d.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() == "package.json" {
			npmDirs = append(npmDirs, filepath.Dir(path))
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}

	if len(npmDirs) == 0 {
		t.Fatal("no package.json found; the walk is not reaching the frontend directories")
	}

	for _, dir := range npmDirs {
		// A directory nested inside one that already has its own go.mod is
		// covered — desktop/frontend/wailsjs, for instance, is generated inside
		// desktop/frontend and inherits its module. Only the root module is a
		// problem, so find the module this directory actually belongs to.
		if enclosingModule(t, dir, root) == root {
			t.Errorf("%s runs npm install but is still in the root module; add a go.mod so npm-shipped Go sources stay out of `go build ./...` (see portal/go.mod)", rel(root, dir))
		}
	}
}

// enclosingModule returns the nearest directory at or above dir that holds a
// go.mod, stopping at root.
func enclosingModule(t *testing.T, dir, root string) string {
	t.Helper()
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		if dir == root {
			t.Fatalf("%s is outside the repository", dir)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatalf("walked past the filesystem root looking for a module above %s", dir)
		}
		dir = parent
	}
}
